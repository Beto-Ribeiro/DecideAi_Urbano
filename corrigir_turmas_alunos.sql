-- 2. Se já existir tabela participacoes ou alunos_votaram, sincroniza a turma correta do aluno
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'participacoes') THEN
    UPDATE public.participacoes p
    SET turma = a.turma, nome = a.nome
    FROM public.alunos a
    WHERE p.ra = a.ra AND (p.turma IS DISTINCT FROM a.turma OR p.nome IS DISTINCT FROM a.nome);
  END IF;

  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'alunos_votaram') THEN
    UPDATE public.alunos_votaram av
    SET turma = a.turma, nome = a.nome
    FROM public.alunos a
    WHERE av.ra = a.ra AND (av.turma IS DISTINCT FROM a.turma OR av.nome IS DISTINCT FROM a.nome);
  END IF;
END $$;

